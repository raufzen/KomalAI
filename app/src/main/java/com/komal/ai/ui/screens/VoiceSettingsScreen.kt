package com.komal.ai.ui.screens

import android.widget.Toast
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.komal.ai.KomalApp
import com.komal.ai.ui.theme.*

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun VoiceSettingsScreen() {
    val context = LocalContext.current
    val app = context.applicationContext as KomalApp
    val prefs = app.preferencesManager

    var appLanguage by remember { mutableStateOf(prefs.appLanguage) }
    var wakeWordInput by remember { mutableStateOf(prefs.wakeWord) }
    var selectedPersona by remember { mutableStateOf(prefs.geminiVoicePersona) }
    var offlineMode by remember { mutableStateOf(prefs.offlineModeEnabled) }
    var isTestingVoice by remember { mutableStateOf(false) }

    val presetWakePhrases = listOf("hey komal", "suno komal", "komal", "ok komal")
    val geminiPersonas = listOf("Aoede", "Kore", "Puck", "Charon", "Fenrir")

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(DarkBackground)
            .padding(16.dp)
            .verticalScroll(rememberScrollState()),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        // Title Card
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = DarkSurface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Text(
                    text = "Gemini AI Voice & Wake Settings",
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextPrimary
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = "Select your Gemini AI voice persona, response language, and background wake phrases. All speech is generated directly by Gemini AI (Zero robotic phone TTS).",
                    fontSize = 13.sp,
                    color = TextSecondary,
                    lineHeight = 18.sp
                )
            }
        }

        // Gemini AI Native Voice Persona Card
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = DarkSurface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Icon(imageVector = Icons.Default.GraphicEq, contentDescription = null, tint = AccentCyan)
                    Text(
                        text = "Gemini AI Voice Persona",
                        fontWeight = FontWeight.SemiBold,
                        fontSize = 15.sp,
                        color = AccentCyanLight
                    )
                }

                Text(
                    text = "Select Komal's natural AI voice persona generated by Gemini:",
                    fontSize = 12.sp,
                    color = TextSecondary
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    geminiPersonas.forEach { persona ->
                        FilterChip(
                            selected = selectedPersona == persona,
                            onClick = {
                                selectedPersona = persona
                                prefs.geminiVoicePersona = persona
                                Toast.makeText(context, "Voice Persona: $persona", Toast.LENGTH_SHORT).show()
                            },
                            label = { Text(persona) }
                        )
                    }
                }

                Text(
                    text = when (selectedPersona) {
                        "Aoede" -> "Aoede: Warm, natural, expressive female voice (Recommended)"
                        "Kore" -> "Kore: Gentle, soothing, relaxed female voice"
                        "Puck" -> "Puck: Youthful, energetic, friendly voice"
                        "Charon" -> "Charon: Deep, calm, mature voice"
                        else -> "Fenrir: Crisp, authoritative, sharp voice"
                    },
                    fontSize = 11.sp,
                    color = AccentEmerald
                )

                // Test Gemini AI Voice Button
                Button(
                    onClick = {
                        isTestingVoice = true
                        val sampleText = if (appLanguage == "english") {
                            "Hello! I am Komal, your autonomous AI phone controller. How can I help you today?"
                        } else {
                            "Hello! Main Komal hoon, aapki autonomous AI phone controller. Boliye main aapki kya madad karun?"
                        }
                        app.voiceSpeaker.speak(sampleText) {
                            isTestingVoice = false
                        }
                    },
                    enabled = !isTestingVoice && prefs.apiKey.isNotBlank(),
                    modifier = Modifier.fillMaxWidth(),
                    colors = ButtonDefaults.buttonColors(containerColor = PrimaryIndigoDark)
                ) {
                    if (isTestingVoice) {
                        CircularProgressIndicator(modifier = Modifier.size(18.dp), color = Color.White, strokeWidth = 2.dp)
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("Speaking via Gemini AI...")
                    } else {
                        Icon(imageVector = Icons.Default.VolumeUp, contentDescription = null)
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("Test Gemini AI Voice ($selectedPersona)")
                    }
                }
            }
        }

        // Offline Fast Mode Card
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = DarkSurface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(16.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = "Offline Fast Mode (Zero Latency)",
                        fontWeight = FontWeight.SemiBold,
                        fontSize = 15.sp,
                        color = TextPrimary
                    )
                    Text(
                        text = "Basic commands (Open WhatsApp, YouTube, Camera, Home, Back, Recents) run instantly via Accessibility Service without calling Gemini API",
                        fontSize = 12.sp,
                        color = if (offlineMode) AccentEmerald else TextSecondary,
                        lineHeight = 16.sp
                    )
                }
                Switch(
                    checked = offlineMode,
                    onCheckedChange = {
                        offlineMode = it
                        prefs.offlineModeEnabled = it
                    },
                    colors = SwitchDefaults.colors(
                        checkedThumbColor = Color.White,
                        checkedTrackColor = AccentEmerald
                    )
                )
            }
        }

        // Assistant Language Selection Card (Hinglish / English)
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = DarkSurface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Text(
                    text = "Response Language",
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 14.sp,
                    color = AccentCyanLight
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    FilterChip(
                        selected = appLanguage == "hinglish",
                        onClick = {
                            appLanguage = "hinglish"
                            prefs.appLanguage = "hinglish"
                            Toast.makeText(context, "Language set to Hinglish", Toast.LENGTH_SHORT).show()
                        },
                        label = { Text("Hinglish (Hindi + English)") },
                        leadingIcon = {
                            if (appLanguage == "hinglish") {
                                Icon(Icons.Default.Check, contentDescription = null, modifier = Modifier.size(16.dp))
                            }
                        }
                    )

                    FilterChip(
                        selected = appLanguage == "english",
                        onClick = {
                            appLanguage = "english"
                            prefs.appLanguage = "english"
                            Toast.makeText(context, "Language set to English", Toast.LENGTH_SHORT).show()
                        },
                        label = { Text("English") },
                        leadingIcon = {
                            if (appLanguage == "english") {
                                Icon(Icons.Default.Check, contentDescription = null, modifier = Modifier.size(16.dp))
                            }
                        }
                    )
                }
            }
        }

        // Wake Word Settings Card
        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = DarkSurface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(
                modifier = Modifier.padding(16.dp),
                verticalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                Text(
                    text = "Wake-up Phrase",
                    fontWeight = FontWeight.SemiBold,
                    fontSize = 14.sp,
                    color = AccentCyanLight
                )

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    presetWakePhrases.forEach { phrase ->
                        FilterChip(
                            selected = wakeWordInput.equals(phrase, ignoreCase = true),
                            onClick = {
                                wakeWordInput = phrase
                                prefs.wakeWord = phrase
                                Toast.makeText(context, "Wake phrase set: '$phrase'", Toast.LENGTH_SHORT).show()
                            },
                            label = { Text(phrase) }
                        )
                    }
                }

                OutlinedTextField(
                    value = wakeWordInput,
                    onValueChange = {
                        wakeWordInput = it
                        prefs.wakeWord = it
                    },
                    label = { Text("Custom Wake Phrase") },
                    modifier = Modifier.fillMaxWidth(),
                    colors = OutlinedTextFieldDefaults.colors(
                        focusedBorderColor = PrimaryIndigo,
                        unfocusedBorderColor = DarkCard,
                        focusedTextColor = TextPrimary,
                        unfocusedTextColor = TextPrimary
                    )
                )
            }
        }
    }
}
